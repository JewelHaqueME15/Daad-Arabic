const DIAC = /[ً-ٰٟـۖ-ۭ]/g;
export function normQ(s) {
  return (s || "")
    .replace(DIAC, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .trim();
}
