/* শেখা শব্দের সাথে মিলিয়ে কুরআন-শব্দ কভারেজ হিসাব করো। */
export function quranCoverage() {
  const known = new Set();
  for (const a of Object.keys(S.words || {})) {
    const n = normQ(a);
    known.add(n); known.add(alStrip(n));
  }
  let cnt = 0, knownOcc = 0, totalOcc = 0;
  const hit = [], miss = [];
  const seen = new Set(); // একই মূল রূপ দুবার গোনা এড়াও (ملك ইত্যাদি)
  for (const e of QURAN_FREQ) {
    const w = normQ(e.w), key = w + "|" + e.bn;
    if (seen.has(key)) continue; seen.add(key);
    totalOcc += e.n;
    if (known.has(w) || known.has(alStrip(w))) { cnt++; knownOcc += e.n; hit.push(e); }
    else miss.push(e);
  }
  const total = QURAN_FREQ.length;
  return {
    known: cnt, total, knownOcc, totalOcc, hit, miss,
    pct: Math.round(cnt / total * 100),
    occPct: totalOcc ? Math.round(knownOcc / totalOcc * 100) : 0,
  };
}
