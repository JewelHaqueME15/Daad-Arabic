let addedV = 0, addedS = 0, files = 0;
for (const [name, add] of Object.entries(ADD)) {
  const p = path.join(DIR, name + ".json");
  if (!fs.existsSync(p)) { console.error("✖ নেই:", name); continue; }
  const L = JSON.parse(fs.readFileSync(p, "utf8"));
  const haveV = new Set(L.vocab.map((v) => strip(v.a)));
  const haveS = new Set(L.sents.map((s) => strip(s.a)));
  for (const [a, b] of (add.v || [])) if (!haveV.has(strip(a))) { L.vocab.push({ a, b }); haveV.add(strip(a)); addedV++; }
  for (const [a, b] of (add.s || [])) if (!haveS.has(strip(a))) { L.sents.push({ a, b }); haveS.add(strip(a)); addedS++; }
  fs.writeFileSync(p, JSON.stringify(L, null, 1) + "\n");
  files++;
}
console.log(`✓ ${files} পাঠে যোগ হলো — ${addedV} শব্দ, ${addedS} বাক্য (পুরনো কিছুই বাদ যায়নি)`);
